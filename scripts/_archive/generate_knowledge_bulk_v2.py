ALL_ENTRIES = (
    PPE_ENTRIES + CHEMICAL_ENTRIES + EQUIPMENT_ENTRIES +
    EMERGENCY_ENTRIES + BIOSAFETY_ENTRIES + RADIATION_ENTRIES +
    VENTILATION_ENTRIES + MANAGEMENT_ENTRIES
)


def main() -> int:
    new_rows = []
    for entry in ALL_ENTRIES:
        if len(entry) != 19:
            print(f"WARNING: skipping entry with {len(entry)} fields: {entry[6][:50] if len(entry) > 6 else entry}")
            continue
        (cat, subcat, lab, risk, hazards, scenario, title, question,
         answer, steps, ppe, forbidden, disposal, first_aid, emergency,
         source_title, source_org, source_url, tags) = entry
        new_rows.append(row(
            cat=cat, subcat=subcat, lab=lab, risk=risk, hazards=hazards,
            scenario=scenario, title=title, question=question, answer=answer,
            steps=steps, ppe=ppe, forbidden=forbidden, disposal=disposal,
            first_aid=first_aid, emergency=emergency,
            source_title=source_title, source_org=source_org,
            source_url=source_url, tags=tags,
        ))

    print(f"New entries generated: {len(new_rows)}")

    existing = []
    if KB_FILE.exists():
        with KB_FILE.open("r", encoding="utf-8-sig", newline="") as f:
            existing = list(csv.DictReader(f))
    print(f"Existing entries: {len(existing)}")

    existing_ids = {r.get("id", "") for r in existing}
    existing_sigs = set()
    for r in existing:
        existing_sigs.add(_sig(r.get("title", ""), r.get("question", "")))

    truly_new = []
    for r in new_rows:
        if r["id"] in existing_ids:
            continue
        s = _sig(r["title"], r["question"])
        if s in existing_sigs:
            continue
        existing_sigs.add(s)
        existing_ids.add(r["id"])
        truly_new.append(r)

    print(f"Truly new (after dedup): {len(truly_new)}")

    if not truly_new:
        print("No new entries to add.")
        return 0

    all_rows = existing + truly_new
    with KB_FILE.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=HEADERS)
        writer.writeheader()
        for row_item in all_rows:
            clean = {h: row_item.get(h, "") for h in HEADERS}
            writer.writerow(clean)

    print(f"Total after merge: {len(all_rows)}")
    # Print category stats
    cats = {}
    for r in all_rows:
        c = r.get("category", "unknown")
        cats[c] = cats.get(c, 0) + 1
    print(f"Category distribution: {cats}")
    print(f"Done. File: {KB_FILE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
