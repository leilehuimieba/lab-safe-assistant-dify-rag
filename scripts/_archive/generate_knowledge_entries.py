# 创建 ID 前缀与计数器
_ID_COUNTER: dict[str, int] = {
    "化学": 2000,
    "设备安全": 3000,
    "通用": 4000,
    "生物": 5000,
    "电气": 6000,
}


def _next_id(category: str, title: str) -> str:
    prefix = {
        "化学": "KB-MSDS",
        "设备安全": "KB-SOP",
        "通用": "KB-GEN",
        "生物": "KB-BIO",
        "电气": "KB-ELEC",
    }.get(category, "KB-EXT")
    _ID_COUNTER[category] = _ID_COUNTER.get(category, 7000) + 1
    return f"{prefix}-{_ID_COUNTER[category]}"


def _make_signature(title: str, question: str) -> str:
    raw = f"{title}||{question}"
    return hashlib.md5(raw.encode("utf-8")).hexdigest()[:10]


def generate_rows(entries: list[dict[str, Any]]) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    seen_ids: set[str] = set()
    seen_sigs: set[str] = set()

    for item in entries:
        cat = str(item.get("category", "通用"))
        title = str(item.get("title", ""))
        question = str(item.get("question", ""))
        sig = _make_signature(title, question)

        if sig in seen_sigs:
            continue
        seen_sigs.add(sig)

        kid = _next_id(cat, title)
        while kid in seen_ids:
            _ID_COUNTER[cat] = _ID_COUNTER.get(cat, 7000) + 1
            kid = _next_id(cat, title)
        seen_ids.add(kid)

        rows.append({
            "id": kid,
            "title": title,
            "category": cat,
            "subcategory": str(item.get("subcategory", "")),
            "lab_type": str(item.get("lab_type", cat)),
            "risk_level": str(item.get("risk_level", "3")),
            "hazard_types": str(item.get("hazard_types", "")),
            "scenario": str(item.get("scenario", "")),
            "question": question,
            "answer": str(item.get("answer", "")),
            "steps": str(item.get("steps", "")),
            "ppe": str(item.get("ppe", "")),
            "forbidden": str(item.get("forbidden", "")),
            "disposal": str(item.get("disposal", "")),
            "first_aid": str(item.get("first_aid", "")),
            "emergency": str(item.get("emergency", "")),
            "legal_notes": str(item.get("legal_notes", "")),
            "references": str(item.get("references", "")),
            "source_type": str(item.get("source_type", "regulatory_standard")),
            "source_title": str(item.get("source_title", "")),
            "source_org": str(item.get("source_org", "")),
            "source_version": str(item.get("source_version", "")),
            "source_date": str(item.get("source_date", "")),
            "source_url": str(item.get("source_url", "")),
            "last_updated": TODAY,
            "reviewer": "auto-generate; pending human review",
            "status": "draft",
            "tags": str(item.get("tags", "")),
            "language": "zh-CN",
        })
    return rows


def main() -> int:
    print(f"Generating entries...")
    new_rows = generate_rows(ENTRIES)
    print(f"  New entries generated: {len(new_rows)}")

    # Load existing entries
    existing_rows: list[dict[str, str]] = []
    if KB_FILE.exists():
        with KB_FILE.open("r", encoding="utf-8-sig", newline="") as f:
            reader = csv.DictReader(f)
            existing_rows = list(reader)
    print(f"  Existing entries: {len(existing_rows)}")

    # Deduplicate by id
    existing_ids = {r.get("id", "") for r in existing_rows}
    truly_new = [r for r in new_rows if r["id"] not in existing_ids]
    print(f"  Truly new (non-duplicate): {len(truly_new)}")

    if not truly_new:
        print("No new entries to add.")
        return 0

    # Append to CSV
    all_rows = existing_rows + truly_new
    with KB_FILE.open("w", encoding="utf-8-sig", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=HEADERS)
        writer.writeheader()
        for row in all_rows:
            # Ensure all headers exist
            clean = {h: row.get(h, "") for h in HEADERS}
            writer.writerow(clean)

    print(f"  Total after merge: {len(all_rows)}")
    print(f"Done. File: {KB_FILE}")
    return 0


